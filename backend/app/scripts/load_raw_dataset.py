"""Bridge the generated raw source files into what the app can consume today.

The raw contract (TRD §6.1) is eight files with the full banking column set.
The walking skeleton only models customers, accounts and transactions, and its
ingestion endpoint takes a narrower CSV, so this script:

1. loads `customers.csv` / `business_customers.csv` / `accounts.csv` into the
   `customer` and `account` master-data tables (which are seeded, not ingested,
   at this stage — see the README's known simplifications), and
2. projects `transactions.csv` onto the ingestion CSV shape, so it can be
   uploaded through the real `POST /ingestion/transactions` endpoint and go
   through batch registration, validation and quarantine like any other file.

What is dropped in step 2 is the gap between the skeleton and the full pipeline,
and the script prints it rather than hiding it.

Before anything is read, the dataset's manifest is checked the way TRD §6.1
requires of any source drop: `synthetic_declaration` must be true (FR-501) and
every file must match its recorded SHA-256. That matters most for the shared
datasets committed under `sample_data/<Tiny|Small|Full>/`, which anyone with
repository access can edit by hand.

Run:
    python -m app.scripts.load_raw_dataset --shared small        # dataset committed to the repo
    python -m app.scripts.load_raw_dataset --profile small       # dataset you generated locally
    python -m app.scripts.load_raw_dataset --raw-dir <dir> --master-data-only
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import re
from datetime import date
from pathlib import Path

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.database import SessionLocal
from app.models.account import Account
from app.models.customer import Customer
from app.models.enums import AccountStatus, EntityType
from app.scripts.generate_raw_dataset import BACKEND_DIR, DEFAULT_OUT
from app.scripts.raw_contract import FILE_SPECS, GENERATOR_VERSION

# Datasets committed to the repository so the whole team loads the same data
# without running the generator.
SHARED_DATASETS = {"tiny": "Tiny", "small": "Small", "full": "Full"}
SHARED_ROOT = BACKEND_DIR / "sample_data"

# The app's ingestion contract (see app/services/ingestion.py).
APP_COLUMNS = (
    "transaction_ref", "account_number", "transaction_date", "amount",
    "currency", "direction", "channel", "counterparty_ref", "description",
)
DIRECTION_MAP = {"IN": "CREDIT", "OUT": "DEBIT"}
# A well-formed ISO 4217 code. Only these can be "foreign currency"; anything
# else (1DR, IDRR, "id r") is a malformed value and belongs in quarantine.
_ISO_CURRENCY = re.compile(r"[A-Z]{3}")


class DatasetRejected(Exception):
    """The dataset fails the TRD §6.1 manifest checks and must not be loaded."""


def check_manifest(raw_dir: Path) -> tuple[dict, list[str]]:
    """TRD §6.1 manifest checks, run before any row is parsed.

    Refuses a dataset that is not declared synthetic (FR-501) or whose files do
    not match their recorded checksums. Returns the manifest and any warnings
    that do not block loading, such as a dataset produced by a different
    generator version than the one in this checkout (TRD §11.7).
    """
    manifest_path = raw_dir / "manifest.json"
    if not manifest_path.exists():
        raise DatasetRejected(f"no manifest.json in {raw_dir}")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))

    if manifest.get("synthetic_declaration") is not True:
        raise DatasetRejected("manifest does not declare synthetic_declaration: true (FR-501)")

    listed = {entry["name"]: entry for entry in manifest.get("files", [])}
    missing = [spec.name for spec in FILE_SPECS if spec.name not in listed]
    if missing:
        raise DatasetRejected(f"manifest does not list: {', '.join(missing)}")
    mismatched = [
        name for name, entry in listed.items()
        if not (raw_dir / name).exists()
        or hashlib.sha256((raw_dir / name).read_bytes()).hexdigest() != entry["sha256"]
    ]
    if mismatched:
        raise DatasetRejected(
            f"file(s) do not match the manifest checksum: {', '.join(mismatched)} — edited or truncated since generation"
        )

    warnings = []
    produced_by = manifest.get("generator_version", "unknown")
    if produced_by != GENERATOR_VERSION:
        warnings.append(
            f"generated by generator {produced_by}; this checkout is {GENERATOR_VERSION}. The same seed now "
            f"produces different data — regenerate if you need the current behaviour"
        )
    return manifest, warnings


def _read(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def load_master_data(db: Session, raw_dir: Path) -> tuple[int, int]:
    """Idempotent: existing customer_ref / account_number rows are left alone."""
    customers = _read(raw_dir / "customers.csv")
    businesses = _read(raw_dir / "business_customers.csv")
    accounts = _read(raw_dir / "accounts.csv")

    existing_customers = set(db.scalars(select(Customer.customer_ref)))
    new_customers: list[Customer] = []
    for row in customers:
        if row["source_customer_id"] in existing_customers:
            continue
        new_customers.append(Customer(
            customer_ref=row["source_customer_id"],
            full_name=row["full_name"],
            entity_type=EntityType.INDIVIDUAL,
            id_number=row["national_id_reference"],
            date_of_birth=date.fromisoformat(row["date_of_birth"]) if row["date_of_birth"] else None,
            country=row["country"] or None,
        ))
    for row in businesses:
        if row["source_business_id"] in existing_customers:
            continue
        new_customers.append(Customer(
            customer_ref=row["source_business_id"],
            full_name=row["legal_name"],
            entity_type=EntityType.BUSINESS,
            id_number=row["registration_number"],
            date_of_birth=None,
            country=row["country"] or None,
        ))
    db.add_all(new_customers)
    db.flush()

    owner_ids = {ref: cid for ref, cid in db.execute(select(Customer.customer_ref, Customer.id))}
    existing_accounts = set(db.scalars(select(Account.account_number)))
    new_accounts: list[Account] = []
    skipped_accounts = 0
    for row in accounts:
        if row["source_account_id"] in existing_accounts:
            continue
        owner = owner_ids.get(row["owner_source_id"])
        if owner is None:
            skipped_accounts += 1
            continue
        new_accounts.append(Account(
            account_number=row["source_account_id"],
            customer_id=owner,
            account_type=row["account_type"],
            currency=row["currency"],
            status=AccountStatus.ACTIVE if row["status"] != "CLOSED" else AccountStatus.CLOSED,
            opened_date=date.fromisoformat(row["opened_date"]) if row["opened_date"] else None,
        ))
    db.add_all(new_accounts)
    db.commit()

    if skipped_accounts:
        print(f"  ! {skipped_accounts} account(s) skipped: owner not present in this dataset")
    return len(new_customers), len(new_accounts)


def project_transactions(raw_dir: Path, out_path: Path) -> dict[str, int]:
    """Project the raw transaction contract onto the app's ingestion CSV.

    Rows are passed through as-is, including the deliberately malformed ones —
    quarantining them is the point (TRD §11.4), so nothing is cleaned here.
    """
    rows = _read(raw_dir / "transactions.csv")
    stats = {"total": len(rows), "written": 0, "non_idr": 0}

    with out_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=APP_COLUMNS, lineterminator="\n")
        writer.writeheader()
        for row in rows:
            # The skeleton has no FX table, so a genuinely foreign-currency row
            # cannot be valued; it is counted and dropped rather than mis-valued.
            # Only a well-formed code counts as foreign: a malformed one such as
            # "1DR" is the INVALID_CURRENCY defect (TRD §11.4) and is passed
            # through so ingestion quarantines it.
            currency = row["currency_original"]
            if _ISO_CURRENCY.fullmatch(currency) and currency != "IDR":
                stats["non_idr"] += 1
                continue
            writer.writerow({
                "transaction_ref": row["source_transaction_reference"],
                "account_number": row["source_account_id"],
                "transaction_date": row["value_datetime"],
                "amount": row["amount_original"],
                "currency": row["currency_original"],
                "direction": DIRECTION_MAP.get(row["direction"], row["direction"]),
                "channel": row["channel"],
                "counterparty_ref": row["counterparty_reference"],
                "description": " ".join(part for part in (
                    row["transaction_type"], row["counterparty_name"],
                    f"[{row['counterparty_country']}]" if row["counterparty_country"] not in ("", "ID") else "",
                ) if part).strip(),
            })
            stats["written"] += 1
    return stats


DROPPED_FIELDS = (
    "business_date", "source_merchant_id", "source_device_id", "ip_address",
    "status_from_source", "transaction_type (folded into description)",
    "counterparty_name (folded into description)", "counterparty_country (folded into description)",
)


def main() -> None:
    parser = argparse.ArgumentParser(description="Load a raw dataset into the walking skeleton.")
    source = parser.add_mutually_exclusive_group()
    source.add_argument("--profile", help="a dataset you generated locally, under sample_data/raw/<profile> (default: small)")
    source.add_argument("--shared", choices=sorted(SHARED_DATASETS),
                        help="a dataset committed to the repository, under sample_data/<Tiny|Small|Full>")
    source.add_argument("--raw-dir", type=Path, help="any dataset directory")
    parser.add_argument("--master-data-only", action="store_true", help="load customers/accounts, skip the CSV projection")
    args = parser.parse_args()

    if args.shared:
        raw_dir = SHARED_ROOT / SHARED_DATASETS[args.shared]
    elif args.raw_dir:
        raw_dir = args.raw_dir
    else:
        raw_dir = DEFAULT_OUT / (args.profile or "small")

    if not (raw_dir / "manifest.json").exists():
        hint = f"python -m app.scripts.generate_raw_dataset --profile {args.profile or 'small'}"
        shared = ", ".join(f"--shared {name}" for name, folder in SHARED_DATASETS.items() if (SHARED_ROOT / folder).exists())
        raise SystemExit(
            f"no dataset at {raw_dir} — generate one with `{hint}`"
            + (f", or load a committed one with {shared}" if shared else "")
        )

    print(f"raw dataset: {raw_dir}")
    try:
        manifest, warnings = check_manifest(raw_dir)
    except DatasetRejected as exc:
        raise SystemExit(f"  REJECTED: {exc}") from exc
    print(
        f"  manifest OK: synthetic, {len(manifest['files'])} file checksums verified · generator "
        f"{manifest.get('generator_version', '?')} · profile {manifest.get('profile', '?')} · "
        f"seed {manifest.get('seed', '?')} · generated {manifest.get('generated_at', '?')[:10]}"
    )
    for warning in warnings:
        print(f"  ! {warning}")

    with SessionLocal() as db:
        customers, accounts = load_master_data(db, raw_dir)
    print(f"  master data loaded: {customers:,} customer(s), {accounts:,} account(s)")

    if args.master_data_only:
        return

    out_path = raw_dir / "transactions_app_format.csv"
    stats = project_transactions(raw_dir, out_path)
    print(f"  projected {stats['written']:,} of {stats['total']:,} transaction(s) -> {out_path}")
    if stats["non_idr"]:
        print(f"  ! {stats['non_idr']:,} non-IDR row(s) dropped: the skeleton has no FX table yet")
    print("  ! not carried across (no column in the skeleton's ingestion contract):")
    for field in DROPPED_FIELDS:
        print(f"      - {field}")
    print("\nNext: upload that file as ROLE_DATA_OPS, from the Overview page or:")
    print(f'  curl -X POST http://localhost:8000/ingestion/transactions -H "Authorization: Bearer <token>" \\')
    print(f'    -F "file=@{out_path}" -F "source_system={manifest["source_system_code"]}" '
          f'-F "business_date={manifest["business_date"]}"')


if __name__ == "__main__":
    main()
